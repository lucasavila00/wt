    #[derive(Clone)]
    struct ContextInstance {
        context: String,
        instance: Instance,
    }

    fn sync(client_config: &ClientConfig, instances: &[ContextInstance]) -> Result<PathBuf> {
        let mut path = None;
        for context in &client_config.contexts {
            let instances = instances
                .iter()
                .filter(|item| item.context == context.name)
                .map(|item| item.instance.clone())
                .collect::<Vec<_>>();
            path = Some(sync_context(client_config, context, &instances)?);
        }
        path.context("test config has no contexts")
    }

    fn local_config() -> ClientConfig {
        ClientConfig {
            contexts: vec![ClientContext {
                name: "local".into(),
                kind: ContextKind::BareMetalLocal,
            }],
        }
    }

    fn normalize_home(contents: &str, home: &Path) -> String {
        contents.replace(&home.display().to_string(), "[HOME]")
    }

    fn context_config(home: &Path, context: &str) -> String {
        fs::read_to_string(home.join(".ssh/wt/contexts").join(context).join("config")).unwrap()
    }

    fn context_known_hosts(home: &Path, context: &str) -> String {
        fs::read_to_string(
            home.join(".ssh/wt/contexts")
                .join(context)
                .join("known_hosts"),
        )
        .unwrap()
    }

