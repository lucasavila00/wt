pub fn sync_context(
    client_config: &ClientConfig,
    context: &ClientContext,
    instances: &[wt_api::Instance],
) -> Result<PathBuf> {
    let home = std::env::var_os("HOME")
        .map(PathBuf::from)
        .context("HOME is not set")?;
    let ssh_dir = home.join(".ssh");
    let managed_dir = ssh_dir.join("wt");
    let contexts_dir = managed_dir.join("contexts");
    ensure_directory(&ssh_dir)?;
    ensure_directory(&managed_dir)?;
    ensure_directory(&contexts_dir)?;
    let main_config_path = ssh_dir.join("config");
    write_context(context, instances, &contexts_dir, &main_config_path)?;
    let config_path = write_root_config(client_config, &managed_dir, &contexts_dir)?;
    ensure_main_include(&main_config_path)?;
    Ok(config_path)
}

fn write_root_config(
    client_config: &ClientConfig,
    managed_dir: &Path,
    contexts_dir: &Path,
) -> Result<PathBuf> {
    let mut config = String::from("# Generated by wt. Do not edit.\n");
    for context in &client_config.contexts {
        config.push_str(&format!(
            "Include {}\n",
            ssh_quote(&contexts_dir.join(&context.name).join("config"))
        ));
    }
    let path = managed_dir.join("config");
    atomic_write(&path, config.as_bytes())?;
    Ok(path)
}

fn ensure_main_include(main_config_path: &Path) -> Result<()> {
    ssh_config::ensure_managed_include(main_config_path).with_context(|| {
        format!(
            "configure WT SSH aliases in {}\nadd `Include ~/.ssh/wt/config` outside any `Host` or `Match` block, then run `wt sync`",
            main_config_path.display()
        )
    })
}

fn write_context(
    context: &ClientContext,
    instances: &[wt_api::Instance],
    contexts_dir: &Path,
    main_config_path: &Path,
) -> Result<()> {
    let directory = contexts_dir.join(&context.name);
    ensure_directory(&directory)?;
    let config_path = directory.join("config");
    let known_hosts_path = directory.join("known_hosts");
    let accessible = instances
        .iter()
        .filter(|instance| {
            matches!(
                instance.status,
                InstanceStatus::Setup | InstanceStatus::Running | InstanceStatus::Error
            ) && instance.ssh.is_some()
                && (instance.status != InstanceStatus::Error
                    || matches!(instance.application, InstanceApplication::Host))
        })
        .collect::<Vec<_>>();
    let mut config = String::from("# Generated by wt. Do not edit.\n");
    let mut known_hosts = String::from("# Generated by wt. Do not edit.\n");
    for instance in accessible {
        let ssh = instance.ssh.as_ref().expect("filtered SSH access");
        validate_ssh_access("guest", &ssh.user, &ssh.host, ssh.port)?;
        if ssh.host_keys.is_empty() {
            bail!("instance {} has incomplete SSH host keys", instance.name);
        }
        let qualified = format!("{}.{}", context.name, instance.name);
        let (proxy_jump, compression) = match &context.kind {
            ContextKind::BareMetalLocal => (String::new(), "no"),
            ContextKind::BareMetalSsh { host } => {
                validate_ssh_host(&context.name, host)?;
                (format!("  ProxyJump {host}\n"), "yes")
            }
        };
        let known_hosts_file = ssh_quote(&known_hosts_path);
        let (guest_alias, app_keys) = match &instance.application {
            InstanceApplication::Devcontainer {
                source, app_ssh, ..
            } => {
                if let Some(app_ssh) = app_ssh {
                    validate_ssh_access("app", &app_ssh.user, "wt-app", app_ssh.port)?;
                }
                let title = world_title(&qualified, source);
                let app_shell = format!("BYOBU_ALT_TITLE='{}' /usr/local/bin/wt-app-shell", title);
                let host_key_alias = format!("{qualified}-host");
                let guest_common = guest_options(
                    ssh,
                    &host_key_alias,
                    &known_hosts_file,
                    compression,
                    &proxy_jump,
                );
                let app_common = app_ssh.as_ref().map(|app_ssh| format!(
                    "  HostName wt-app\n  User {}\n  Port {}\n  HostKeyAlias {}-vs\n  UserKnownHostsFile {}\n  StrictHostKeyChecking yes\n  Compression {compression}\n  ServerAliveInterval 30\n  ServerAliveCountMax 3\n  PasswordAuthentication no\n  KbdInteractiveAuthentication no\n  SetEnv TERM=xterm-256color\n  ProxyCommand ssh -F {} -o Compression=no {}-host /usr/local/bin/wt-app-proxy\n",
                    app_ssh.user,
                    app_ssh.port,
                    qualified,
                    known_hosts_file,
                    ssh_quote(main_config_path),
                    qualified,
                ));
                config.push_str(&format!("\nHost {qualified}-host\n{guest_common}\nHost {qualified}\n{guest_common}  RequestTTY force\n  RemoteCommand {app_shell}\n"));
                if let Some(app_common) = &app_common {
                    config.push_str(&format!("\nHost {qualified}-vs\n{app_common}"));
                }
                (
                    host_key_alias,
                    app_ssh
                        .iter()
                        .flat_map(|ssh| &ssh.host_keys)
                        .collect::<Vec<_>>(),
                )
            }
            InstanceApplication::Host => {
                let host_shell =
                    format!("BYOBU_ALT_TITLE='{qualified}' /usr/local/bin/wt-host-shell");
                let guest_common =
                    guest_options(ssh, &qualified, &known_hosts_file, compression, &proxy_jump);
                let host_common = format!("{guest_common}  ForwardAgent yes\n");
                config.push_str(&format!(
                    "\nHost {qualified}\n{host_common}  RequestTTY force\n  RemoteCommand {host_shell}\n\nHost {qualified}-vs\n{host_common}"
                ));
                (qualified.clone(), Vec::new())
            }
        };
        for key in &ssh.host_keys {
            append_known_host(&mut known_hosts, &guest_alias, key, instance)?;
        }
        for key in app_keys {
            append_known_host(&mut known_hosts, &format!("{qualified}-vs"), key, instance)?;
        }
    }
    atomic_write(&config_path, config.as_bytes())?;
    atomic_write(&known_hosts_path, known_hosts.as_bytes())?;
    Ok(())
}

fn guest_options(
    ssh: &wt_api::SshAccess,
    host_key_alias: &str,
    known_hosts_file: &str,
    compression: &str,
    proxy_jump: &str,
) -> String {
    format!(
        "  HostName {}\n  User {}\n  Port {}\n  HostKeyAlias {host_key_alias}\n  UserKnownHostsFile {known_hosts_file}\n  StrictHostKeyChecking yes\n  Compression {compression}\n  ServerAliveInterval 30\n  ServerAliveCountMax 3\n  PasswordAuthentication no\n  KbdInteractiveAuthentication no\n{proxy_jump}",
        ssh.host, ssh.user, ssh.port,
    )
}

fn append_known_host(
    known_hosts: &mut String,
    alias: &str,
    key: &str,
    instance: &wt_api::Instance,
) -> Result<()> {
    let mut fields = key.split_whitespace();
    let kind = fields.next().unwrap_or_default();
    let data = fields.next().unwrap_or_default();
    if kind.is_empty() || data.is_empty() {
        bail!("instance {} has an invalid SSH host key", instance.name);
    }
    known_hosts.push_str(&format!("{alias} {kind} {data}\n"));
    Ok(())
}

fn validate_ssh_access(label: &str, user: &str, host: &str, port: u16) -> Result<()> {
    let safe_user = !user.is_empty()
        && user
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'.' | b'_' | b'-'));
    if !safe_user {
        bail!("{label} SSH user is not safe for managed OpenSSH configuration")
    }
    let safe_host = !host.is_empty()
        && host.bytes().all(|byte| {
            byte.is_ascii_alphanumeric() || matches!(byte, b'.' | b':' | b'-' | b'[' | b']')
        });
    if !safe_host {
        bail!("{label} SSH host is not safe for managed OpenSSH configuration")
    }
    if port == 0 {
        bail!("{label} SSH port must be greater than zero")
    }
    Ok(())
}

fn world_title(qualified: &str, source: &str) -> String {
    match repository_name(source) {
        Some(repository) => format!("{qualified} - {repository}"),
        None => qualified.to_owned(),
    }
}

pub fn repository_name(source: &str) -> Option<&str> {
    let path = if let Some(rest) = source.strip_prefix("ssh://") {
        rest.split_once('/')?.1
    } else {
        source.split_once(':')?.1
    };
    let repository = path.trim_end_matches('/').rsplit('/').next()?;
    let repository = repository.strip_suffix(".git").unwrap_or(repository);
    (!repository.is_empty()
        && repository
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'.' | b'_' | b'-')))
    .then_some(repository)
}

fn ensure_directory(path: &Path) -> Result<()> {
    fs::create_dir_all(path).with_context(|| format!("create {}", path.display()))?;
    fs::set_permissions(path, fs::Permissions::from_mode(0o700))
        .with_context(|| format!("set permissions on {}", path.display()))
}

fn atomic_write(path: &Path, contents: &[u8]) -> Result<()> {
    let temporary = path.with_extension("wt-new");
    let mut file = OpenOptions::new()
        .write(true)
        .create_new(true)
        .mode(0o600)
        .open(&temporary)
        .with_context(|| format!("create {}", temporary.display()))?;
    let result = (|| {
        file.write_all(contents)?;
        file.sync_all()?;
        fs::rename(&temporary, path)?;
        Ok::<_, std::io::Error>(())
    })();
    if result.is_err() {
        let _ = fs::remove_file(&temporary);
    }
    result.with_context(|| format!("atomically update {}", path.display()))
}

fn ssh_quote(path: &Path) -> String {
    format!(
        "\"{}\"",
        path.display()
            .to_string()
            .replace('\\', "\\\\")
            .replace('\"', "\\\"")
    )
}

