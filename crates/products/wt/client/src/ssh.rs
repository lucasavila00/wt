    #[test]
    fn concurrent_syncs_publish_one_inventory_generation() {
        let temp = tempfile::tempdir().unwrap();
        let config = local_config();
        let inventories = (0..16)
            .map(|index| vec![instance(&format!("world-{index}"), &format!("KEY{index}"))])
            .collect::<Vec<_>>();
        let barrier = std::sync::Barrier::new(inventories.len());

        std::thread::scope(|scope| {
            let threads = inventories
                .iter()
                .map(|inventory| {
                    scope.spawn(|| {
                        barrier.wait();
                        sync_in_home(temp.path(), &config, inventory)
                    })
                })
                .collect::<Vec<_>>();
            for thread in threads {
                thread.join().unwrap().unwrap();
            }
        });

        let managed_dir = temp.path().join(".ssh/wt");
        let published_config = fs::read_to_string(managed_dir.join("config")).unwrap();
        let published_known_hosts = fs::read_to_string(managed_dir.join("known_hosts")).unwrap();
        assert!((0..inventories.len()).any(|generation| {
            published_config.contains(&format!("\nHost local.world-{generation}\n"))
                && published_known_hosts.contains(&format!(
                    "\nlocal.world-{generation} ssh-ed25519 KEY{generation}\n"
                ))
        }));
        assert_eq!(
            fs::metadata(managed_dir.join("inventory.lock"))
                .unwrap()
                .permissions()
                .mode()
                & 0o777,
            0o600
        );
    }

    #[test]
    fn sync_bootstraps_main_config_and_removes_stale_worlds() {
        let _lock = HOME_LOCK.lock().unwrap();
        let temp = tempfile::tempdir().unwrap();
        std::env::set_var("HOME", temp.path());
        fs::create_dir(temp.path().join(".ssh")).unwrap();
        let main_config = "Include ~/.ssh/wt/config\nHost personal\n  HostName example.test\n";
        fs::write(temp.path().join(".ssh/config"), main_config).unwrap();
        let instance = Instance {
            id: Uuid::new_v4(),
            name: InstanceName::parse("repo-feature").unwrap(),
            owner: "lucas".into(),
            status: InstanceStatus::Running,
            vcpus: 2,
            memory_mib: 4096,
            disk_gib: 32,
            guest_ip: Some("192.0.2.2".into()),
            last_error: None,
            ssh: Some(SshAccess {
                user: "wt".into(),
                host: "192.0.2.2".into(),
                port: 22,
                host_keys: vec!["ssh-ed25519 AAAATEST guest".into()],
            }),
        };
        let mut replacement_instance = instance.clone();
        replacement_instance.id = Uuid::new_v4();
        replacement_instance.ssh.as_mut().unwrap().host_keys =
            vec!["ssh-ed25519 AAAAREPLACEMENT guest".into()];
        let client_config = local_config();
        sync(
            &client_config,
            &[ContextInstance {
                context: "local".into(),
                agent_tool_report_count: 0,
                disk_usage_bytes: None,
                instance,
            }],
        )
        .unwrap();
        let managed = fs::read_to_string(temp.path().join(".ssh/wt/config")).unwrap();
        insta::assert_snapshot!(
            "unique_world_ssh_config",
            normalize_home(&managed, temp.path())
        );
        sync(
            &client_config,
            &[ContextInstance {
                context: "local".into(),
                agent_tool_report_count: 0,
                disk_usage_bytes: None,
                instance: replacement_instance,
            }],
        )
        .unwrap();
        let known_hosts = fs::read_to_string(temp.path().join(".ssh/wt/known_hosts")).unwrap();
        insta::assert_snapshot!(known_hosts, @r###"
        # Generated by wt sync. Do not edit.
        local.repo-feature ssh-ed25519 AAAAREPLACEMENT
        "###);
        sync(&client_config, &[]).unwrap();
        let main = fs::read_to_string(temp.path().join(".ssh/config")).unwrap();
        assert_eq!(main, main_config);
        let managed = fs::read_to_string(temp.path().join(".ssh/wt/config")).unwrap();
        assert!(!managed.contains("repo-feature"));
    }

