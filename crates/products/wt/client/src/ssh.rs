use std::path::{Path, PathBuf};
use wt_control_protocol::InstanceStatus;

pub fn sync(client_config: &ClientConfig, instances: &[ContextInstance]) -> Result<PathBuf> {
    let home = std::env::var_os("HOME")
        .map(PathBuf::from)
        .context("HOME is not set")?;
    sync_in_home(&home, client_config, instances)
}

fn sync_in_home(
    home: &Path,
    client_config: &ClientConfig,
    instances: &[ContextInstance],
) -> Result<PathBuf> {
    let ssh_dir = home.join(".ssh");
    let managed_dir = ssh_dir.join("wt");
    ensure_directory(&ssh_dir)?;
    ensure_directory(&managed_dir)?;
    let lock_path = managed_dir.join("inventory.lock");
    let lock_file = OpenOptions::new()
        .read(true)
        .write(true)
        .create(true)
        .truncate(false)
        .mode(0o600)
        .open(&lock_path)
        .with_context(|| format!("open {}", lock_path.display()))?;
    let _lock = Flock::lock(lock_file, FlockArg::LockExclusive)
        .map_err(|(_, error)| error)
        .with_context(|| format!("lock {}", lock_path.display()))?;
    let config_path = managed_dir.join("config");
    let known_hosts_path = managed_dir.join("known_hosts");
    let main_config_path = ssh_dir.join("config");

    let accessible = instances.iter().filter(|item| has_alias(item));
    let counts = name_counts(instances);
    let mut config = String::from("# Generated by wt sync. Do not edit.\n");
    let mut known_hosts = String::from("# Generated by wt sync. Do not edit.\n");
    for item in accessible {
        let instance = &item.instance;
        let ssh = instance.ssh.as_ref().expect("filtered SSH access");
        if ssh.host_keys.is_empty() {
            bail!("instance {} has incomplete SSH host keys", instance.name);
        }
        let qualified = item.qualified_name();
        let context = client_config
            .context(&item.context)
            .with_context(|| format!("missing client context {}", item.context))?;
        let (proxy_jump, compression) = match &context.kind {
            ContextKind::BareMetalLocal => (String::new(), "no"),
            ContextKind::BareMetalSsh { host } => {
                validate_ssh_host(&context.name, host)?;
                (format!("  ProxyJump {host}\n"), "yes")
            }
        };
        let known_hosts_file = ssh_quote(&known_hosts_path);
        let unique_name = counts.get(instance.name.as_str()) == Some(&1);
        let host_shell = format!("BYOBU_ALT_TITLE='{qualified}' /usr/local/bin/wt-host-shell");
        let guest_common =
            guest_options(ssh, &qualified, &known_hosts_file, compression, &proxy_jump);
        config.push_str(&format!(
            "\nHost {qualified}\n{guest_common}  RequestTTY force\n  RemoteCommand {host_shell}\n\nHost {qualified}-direct\n{guest_common}"
        ));
        if unique_name {
            config.push_str(&format!(
                "\nHost {}\n{guest_common}  RequestTTY force\n  RemoteCommand {host_shell}\n\nHost {}-direct\n{guest_common}",
                instance.name, instance.name
            ));
        }
        for key in &ssh.host_keys {
            append_known_host(&mut known_hosts, &qualified, key, instance)?;
        }
    }
    ssh_config::ensure_managed_include(&main_config_path).with_context(|| {
        format!(
            "configure WT SSH aliases in {}\nadd `Include ~/.ssh/wt/config` outside any `Host` or `Match` block, then run `wt sync`",
            main_config_path.display()
        )
    })?;
    atomic_file::replace(&config_path, config.as_bytes())?;
    atomic_file::replace(&known_hosts_path, known_hosts.as_bytes())?;
    Ok(config_path)
}

pub fn has_alias(item: &ContextInstance) -> bool {
    matches!(
        item.instance.status,
        InstanceStatus::Running | InstanceStatus::Error
    ) && item.instance.ssh.is_some()
}

fn guest_options(
    ssh: &wt_control_protocol::SshAccess,
    host_key_alias: &str,
    known_hosts_file: &str,
    compression: &str,
    proxy_jump: &str,
) -> String {
    format!(
        "  HostName {}\n  User {}\n  Port {}\n  HostKeyAlias {host_key_alias}\n  UserKnownHostsFile {known_hosts_file}\n  StrictHostKeyChecking yes\n  Compression {compression}\n  ServerAliveInterval 30\n  ServerAliveCountMax 3\n  PasswordAuthentication no\n  KbdInteractiveAuthentication no\n{proxy_jump}",
        ssh.host, ssh.user, ssh.port,
    )
}

fn append_known_host(
    known_hosts: &mut String,
    alias: &str,
    key: &str,
    instance: &wt_control_protocol::Instance,
) -> Result<()> {
    let mut fields = key.split_whitespace();
    let kind = fields.next().unwrap_or_default();
    let data = fields.next().unwrap_or_default();
    if kind.is_empty() || data.is_empty() {
        bail!("instance {} has an invalid SSH host key", instance.name);
    }
    known_hosts.push_str(&format!("{alias} {kind} {data}\n"));
    Ok(())
}

fn ensure_directory(path: &Path) -> Result<()> {
    fs::create_dir_all(path).with_context(|| format!("create {}", path.display()))?;
    fs::set_permissions(path, fs::Permissions::from_mode(0o700))
        .with_context(|| format!("set permissions on {}", path.display()))
}

fn ssh_quote(path: &Path) -> String {
    format!(
        "\"{}\"",
        path.display()
            .to_string()
            .replace('\\', "\\\\")
            .replace('\"', "\\\"")
    )
}

